class RayoLocalizationsDelegate
    extends LocalizationsDelegate<RayoLocalizations> {
  const RayoLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => ['en', 'fr', 'ar'].contains(locale.languageCode);

  @override
  Future<RayoLocalizations> load(Locale locale) async {
    return RayoLocalizations(locale);
  }

  @override
  bool shouldReload(RayoLocalizationsDelegate old) => false;
}

extension BuildContextLocalizations on BuildContext {
  String tr(String key) => RayoLocalizations.of(this).tr(key);
}
